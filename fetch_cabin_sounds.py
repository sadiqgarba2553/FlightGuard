"""Fetch recorded cabin audio with original bytes and FlyByWire licence notices."""
from pathlib import Path
import concurrent.futures,hashlib,json,shutil,sys,urllib.parse,urllib.request
app=Path(sys.argv[1]).resolve()
revision='b4c58ff3875ef00b61a680ccbb35acc4bcebc2ef'
mapping={
 'boarding-welcome':'A_Welcome.wav','boarding-ambience':'boarding.wav',
 'boarding-complete':'boardingcompleted.wav','safety-briefing':'Safety.wav',
 'taxi-ambience':'taxi.wav','before-takeoff':'CAPTAIN-CABINCREW-SEATS-FOR-TAKEOFF.wav',
 'cabin-landing':'A_Prepare for landing.wav','cabin-seats-landing':'CAPTAIN-CABINCREW-SEATS-FOR-LANDING.wav',
 'after-landing':'A_After landing.wav','doors-disarm':'disarmdoors.wav','deboarding':'Deboarding.wav'}
folder=app/'Sounds/Shared Cabin';folder.mkdir(parents=True,exist_ok=True)
def fetch(item):
 cue,name=item;original='sound/Originals/SFX/'+name
 url=f'https://raw.githubusercontent.com/flybywiresim/a32nx-wwise/{revision}/'+urllib.parse.quote(original)
 data=urllib.request.urlopen(urllib.request.Request(url,headers={'User-Agent':'FlightGuard/0.5'}),timeout=90).read()
 if data[:4]!=b'RIFF' or data[8:12]!=b'WAVE' or not 512<len(data)<=20*1024*1024:raise ValueError(cue+' invalid WAV/size')
 (folder/(cue+'.wav')).write_bytes(data)
 return dict(family='Shared Cabin',cue=cue,source_url=url,original_path=original,revision=revision,license='CC-BY-NC-SA-4.0',bytes=len(data),sha256=hashlib.sha256(data).hexdigest(),authenticity='Original upstream simulator cabin recording. Shared across supported airliners; may contain aircraft/airline wording. No OEM or universal airline voice claim. No speech synthesis generated by FlightGuard.')
with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:rows=list(pool.map(fetch,mapping.items()))
for row in rows:print(row['cue'],row['bytes'],flush=True)
manifest=app/'sound-provenance.json'
old=json.loads(manifest.read_text(encoding='utf-8-sig'))
old=[r for r in old if r['family']!='Shared Cabin']
manifest.write_text(json.dumps(old+rows,indent=2),encoding='utf-8')
shutil.copy2(app/'SoundSources/FBW/LICENSE.txt',folder/'LICENSE.txt')
(folder/'ATTRIBUTION.md').write_text(f'''# Shared recorded cabin pack

FlyByWire Simulations A32NX Wwise project and contributors.
Source: https://github.com/flybywiresim/a32nx-wwise/tree/{revision}
Licence: CC BY-NC-SA 4.0 (noncommercial, attribution, share alike); see LICENSE.txt.
Original unmodified WAV bytes are included, renamed to cue IDs; source mappings and hashes are in sound-provenance.json.
These are shared simulator recordings, not aircraft-specific OEM voices or custom airline announcements. Some may refer to their original aircraft/airline.
Boarding, cabin safety, taxi and arrival scheduling is FlightGuard's independently implemented simulator logic.
''',encoding='utf-8')
print('Cabin recordings fetched:',len(rows),flush=True)
